const fs = require('fs');
const out = JSON.parse(fs.readFileSync('C:/Users/VR/AppData/Local/Temp/claude/C--Users-VR/c264b828-eb04-4d32-9ce0-c6d8d6164eaf/tasks/wh20i8nv4.output', 'utf8'));
const r = out.result;

const sevOrder = { high: 0, medium: 1, low: 2 };
const flaws = [...r.flaws.confirmed];
flaws.sort((a, b) => (sevOrder[a.severity] - sevOrder[b.severity]) || a.lens.localeCompare(b.lens));
const features = [...r.features.confirmed];
const effortOrder = { small: 0, medium: 1, large: 2 };
features.sort((a, b) => (effortOrder[a.effort] - effortOrder[b.effort]) || a.lens.localeCompare(b.lens));

const all = [];
flaws.forEach(f => all.push({ ...f, kind: 'flaw' }));
features.forEach(f => all.push({ ...f, kind: 'feature' }));
all.forEach((f, i) => { f.taskId = 'P18-' + String(i + 1).padStart(3, '0'); });

function cluster(f) {
  if (f.kind === 'feature') {
    if (f.lens === 'observability-tools') return 'X_feat_observ';
    if (f.lens === 'operator-accelerators') return 'X_feat_accel';
    if (f.lens === 'mcp-resources') return 'X_feat_resource';
    if (f.lens === 'in-mcp-docs') return 'X_feat_help';
    return 'X_feat_tools';
  }
  const file = (f.file || '').toLowerCase().replace(/\\/g, '/');
  if (file.includes('lacertesessionmanager') || file.includes('resilience/autoreconnect')) return 'A_session';
  if (file.includes('simulationstore')) return 'B_simstore';
  if (file.includes('fieldaccessmaploader') || file.includes('fieldaccessdumper')) return 'C_schema';
  if (file.includes('workflowprompts')) return 'D_prompts';
  if (file.includes('clientstools') || file.includes('sessiontools')) return 'E_tools_session';
  if (file.includes('fieldwrite') || file.includes('detailstools')) return 'F_writetools';
  if (file.includes('wirelog')) return 'G_logging';
  if (file.includes('tools/')) return 'E_tools_session';
  return 'Z_misc';
}
all.forEach(f => { f.cluster = cluster(f); });
fs.writeFileSync('C:/Users/VR/Projects/LacertMCP/audit-findings-r5.json', JSON.stringify(all, null, 2));

let body = '\n---\n\n## Phase 18 — Round-5 deep flaws + aspirational features (2026-06-05)\n\n';
body += 'Generated by an 11-lens round-5 audit (70 agents total): 6 deep flaw-hunt lenses found 23 confirmed flaws (10 high, 12 medium, 1 low); 5 aspirational feature lenses surfaced 13 high-value feature additions. ';
body += 'Most consequential flaw: dry-run + idempotency cache composition silently no-ops real writes (P18-001). ';
body += 'Full context in `audit-findings-r5.json`. Ordering: flaws first by severity, then features by effort.\n';

body += '\n## FLAWS\n';
let prev = '';
for (const f of all.filter(x => x.kind === 'flaw')) {
  if (f.severity !== prev) {
    body += '\n### ' + f.severity.toUpperCase() + ' severity\n\n';
    prev = f.severity;
  }
  const title = (f.title || '').replace(/\n/g, ' ').trim();
  body += '- [ ] **' + f.taskId + '** [' + f.lens + ' / ' + f.cluster + '] ' + title + '\n';
  body += '  - File(s): ' + ((f.file || 'n/a').replace(/\\/g, '/')) + ' (line ' + (f.line || 'n/a') + ')\n';
  const impact = (f.impact || '').replace(/\n/g, ' ').trim().slice(0, 280);
  if (impact) body += '  - Impact: ' + impact + '\n';
  const rec = (f.verdict && f.verdict.refinedRecommendation ? f.verdict.refinedRecommendation : (f.recommendation || '')).replace(/\n/g, ' ').trim();
  body += '  - Do: ' + rec.slice(0, 500) + (rec.length > 500 ? '...' : '') + '\n';
}

body += '\n## FEATURES\n';
prev = '';
for (const f of all.filter(x => x.kind === 'feature')) {
  if (f.effort !== prev) {
    body += '\n### ' + (f.effort || 'medium').toUpperCase() + ' effort\n\n';
    prev = f.effort;
  }
  const title = (f.title || '').replace(/\n/g, ' ').trim();
  body += '- [ ] **' + f.taskId + '** [' + f.lens + ' / ' + f.cluster + '] ' + title + '\n';
  body += '  - Motivation: ' + ((f.motivation || '').replace(/\n/g, ' ').trim().slice(0, 280)) + '\n';
  const design = (f.verdict && f.verdict.refinedDesign ? f.verdict.refinedDesign : (f.design || '')).replace(/\n/g, ' ').trim();
  body += '  - Design: ' + design.slice(0, 500) + (design.length > 500 ? '...' : '') + '\n';
}

fs.writeFileSync('C:/Users/VR/Projects/LacertMCP/.todo-phase18-addendum.md', body);
console.log('Wrote audit-findings-r5.json (' + all.length + ' entries) and .todo-phase18-addendum.md');
const cc = {};
all.forEach(f => { (cc[f.cluster] ||= []).push(f.taskId); });
console.log('\nClusters:');
Object.entries(cc).sort().forEach(([k, v]) => console.log(' ', k.padEnd(20), v.length.toString().padStart(2), v.join(',')));
