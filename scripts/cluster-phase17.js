const fs = require('fs');
const out = JSON.parse(fs.readFileSync('C:/Users/VR/AppData/Local/Temp/claude/C--Users-VR/c264b828-eb04-4d32-9ce0-c6d8d6164eaf/tasks/wo0a18m03.output', 'utf8'));
const findings = out.result.confirmed;

const sevOrder = { high: 0, medium: 1, low: 2 };
findings.sort((a, b) => (sevOrder[a.severity] - sevOrder[b.severity]) || a.lens.localeCompare(b.lens));
findings.forEach((f, i) => { f.taskId = 'P17-' + String(i + 1).padStart(3, '0'); });

function cluster(f) {
  const file = (f.file || '').toLowerCase().replace(/\\/g, '/');
  if (file.includes('workflowprompts') || file.includes('prompts/')) return 'A_prompts';
  if (file.includes('syntheticstatuscodes') || file.includes('statuscodes')) return 'B_errors';
  if (file.includes('parity/') || file.includes('lacertmcp.tests/')) return 'C_tests';
  if (file.includes('heartbeatwriter') || file.includes('diagnostics/')) return 'D_heartbeat';
  if (file.includes('lacertesessionmanager')) return 'E_session';
  if (file.includes('readme.md')) return 'F_readme';
  if (file.includes('fieldwritebulktools')) return 'G_bulk';
  if (file.includes('pathvalidation')) return 'H_pathval';
  if (file.includes('registration') || file.includes('appidstore')) return 'I_appid';
  if (file.includes('directory.build') || file.includes('.github') || file.includes('release.ps1')) return 'J_build';
  return 'Z_misc';
}
findings.forEach(f => { f.cluster = cluster(f); });
fs.writeFileSync('C:/Users/VR/Projects/LacertMCP/audit-findings-r4.json', JSON.stringify(findings, null, 2));

let body = '\n---\n\n## Phase 17 — Round-4 post-saturation audit (2026-06-04)\n\n';
body += 'Generated by a 10-lens post-saturation audit (40 agents, 17/30 confirmed under double-strict gate: novel + materiallyImproves). ';
body += 'Two real round-3 regressions surfaced (prompts not renamed when params were renamed; remediation strings same drift). ';
body += 'Full context in `audit-findings-r4.json`. Ordering: severity, then lens.\n';

let prev = '';
for (const f of findings) {
  if (f.severity !== prev) {
    body += '\n### ' + f.severity.toUpperCase() + ' severity\n\n';
    prev = f.severity;
  }
  const title = (f.title || '').replace(/\n/g, ' ').trim();
  body += '- [ ] **' + f.taskId + '** [' + f.lens + ' / ' + f.cluster + '] ' + title + '\n';
  body += '  - File(s): ' + ((f.file || 'n/a').replace(/\\/g, '/')) + ' (line ' + (f.line || 'n/a') + ')\n';
  const impact = (f.userOrOpsImpact || '').replace(/\n/g, ' ').trim().slice(0, 280);
  if (impact) body += '  - Impact: ' + impact + '\n';
  const rec = (f.verdict && f.verdict.refinedRecommendation ? f.verdict.refinedRecommendation : (f.recommendation || '')).replace(/\n/g, ' ').trim();
  body += '  - Do: ' + rec.slice(0, 500) + (rec.length > 500 ? '...' : '') + '\n';
}

fs.writeFileSync('C:/Users/VR/Projects/LacertMCP/.todo-phase17-addendum.md', body);
console.log('Wrote audit-findings-r4.json (' + findings.length + ' entries) and .todo-phase17-addendum.md');
const cc = {};
findings.forEach(f => { (cc[f.cluster] ||= []).push(f.taskId); });
console.log('\nClusters:');
Object.entries(cc).sort().forEach(([k, v]) => console.log(' ', k.padEnd(15), v.length, '|', v.join(',')));
