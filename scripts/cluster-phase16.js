// Cluster round-3 findings, save audit-findings-r3.json, generate Todo.md addendum
const fs = require('fs');
const out = JSON.parse(fs.readFileSync('C:/Users/VR/AppData/Local/Temp/claude/C--Users-VR/c264b828-eb04-4d32-9ce0-c6d8d6164eaf/tasks/wailg87d1.output', 'utf8'));
const findings = out.result.confirmed;

const sevOrder = { high: 0, medium: 1, low: 2 };
findings.sort((a, b) => (sevOrder[a.severity] - sevOrder[b.severity]) || a.lens.localeCompare(b.lens));
findings.forEach((f, i) => { f.taskId = 'P16-' + String(i + 1).padStart(3, '0'); });

function cluster(f) {
  const file = (f.file || '').toLowerCase().replace(/\\/g, '/');
  // Cross-tool naming refactors get their own cluster
  if (/stateabbrev|stateabbr|taxyear.+year|year.+taxyear|paramet/.test(f.title.toLowerCase()) && f.lens === 'llm-tool-usability') return 'X_naming_xtool';
  if (f.lens === 'cross-tool-consistency' || f.lens === 'naming-quality') return 'X_naming_xtool';

  if (file.includes('wraptoolhandler') || file.includes('wirelog')) return 'A_logging';
  if (file.includes('lacertesessionmanager')) return 'B_session';
  if (file.includes('bridge/')) return 'C_bridge';
  if (file.includes('odbc/')) return 'D_odbc';
  if (file.includes('errors/')) return 'E_errors';
  if (file.includes('schema/')) return 'F_schema';
  if (file.includes('prompts/')) return 'G_prompts';
  if (file.includes('tools/details')) return 'J_details';
  if (file.includes('tools/health')) return 'J_health';
  if (file.includes('tools/clientstools') || file.includes('tools/clients.')) return 'J_clients';
  if (file.includes('tools/sessiontools')) return 'J_sessiontools';
  if (file.includes('tools/createclienttools')) return 'J_createtools';
  if (file.includes('tools/fieldwrite') || file.includes('tools/updatereturn')) return 'J_writetools';
  if (file.includes('tools/metadatatools')) return 'J_metatools';
  if (file.includes('tools/tables') || file.includes('tools/states') || file.includes('tools/forms') || file.includes('tools/status') || file.includes('tools/subclients') || file.includes('tools/efile') || file.includes('tools/fieldwritebulk') || file.includes('tools/schemareload')) return 'J_tools_other';
  if (file.includes('cli/commands/') || file.includes('lacertmcp.cli/commands') || file.includes('cli/program') || file.includes('cli/storage')) return 'K_cli';
  if (file.includes('server/program')) return 'L_program';
  if (file.includes('diagnostics/')) return 'L_program';
  if (file.includes('lacertmcp.tests/') || file.includes('tests/')) return 'M_tests';
  if (file.includes('readme.md')) return 'N_readme';
  if (file.includes('architecture.md')) return 'N_arch';
  if (file.includes('claude.md')) return 'N_claude';
  if (file.includes('decisions.md')) return 'N_decisions';
  if (file.includes('requirements.md')) return 'N_req';
  if (file.includes('regression_checklist.md')) return 'N_regression';
  if (file.includes('acceptance_criteria.md')) return 'N_acceptance';
  if (file.includes('todo.md')) return 'N_todo';
  if (file.includes('handoff.md')) return 'N_handoff';
  if (file.includes('.env.example')) return 'N_env';
  if (file.includes('lacerte_mcp_structure_spec') || file.includes('docs/')) return 'N_docs';
  if (file.includes('.github') || file.includes('scripts/') || file.includes('csproj') || file.includes('app.config') || file.includes('.editorconfig') || file.includes('.gitignore')) return 'O_dx';
  return 'Z_misc';
}
findings.forEach(f => { f.cluster = cluster(f); });
fs.writeFileSync('C:/Users/VR/Projects/LacertMCP/audit-findings-r3.json', JSON.stringify(findings, null, 2));

// Build Todo.md addendum
let out2 = '\n---\n\n## Phase 16 — Round-3 usability audit (2026-05-30)\n\n';
out2 += 'Generated by a 14-lens usability + perfection audit + adversarial verification (115 agents, 85/101 confirmed). ';
out2 += 'Full context in `audit-findings-r3.json`. Ordering: severity, then lens. Verifier required `meaningfullyImproves` to be true (no bikeshedding).\n';

let prev = '';
for (const f of findings) {
  if (f.severity !== prev) {
    out2 += '\n### ' + f.severity.toUpperCase() + ' severity\n\n';
    prev = f.severity;
  }
  const title = (f.title || '').replace(/\n/g, ' ').trim();
  out2 += '- [ ] **' + f.taskId + '** [' + f.lens + ' / ' + f.cluster + '] ' + title + '\n';
  out2 += '  - File(s): ' + ((f.file || 'n/a').replace(/\\/g, '/')) + ' (line ' + (f.line || 'n/a') + ')\n';
  const impact = (f.userImpact || '').replace(/\n/g, ' ').trim().slice(0, 280);
  if (impact) out2 += '  - Impact: ' + impact + '\n';
  const rec = (f.verdict && f.verdict.refinedRecommendation ? f.verdict.refinedRecommendation : (f.recommendation || '')).replace(/\n/g, ' ').trim();
  out2 += '  - Do: ' + rec.slice(0, 500) + (rec.length > 500 ? '...' : '') + '\n';
}

fs.writeFileSync('C:/Users/VR/Projects/LacertMCP/.todo-phase16-addendum.md', out2);
console.log('Wrote audit-findings-r3.json (' + findings.length + ' entries) and .todo-phase16-addendum.md (' + out2.length + ' chars)');
console.log('Task IDs: P16-001 through P16-' + String(findings.length).padStart(3, '0'));
const cc = {};
findings.forEach(f => { (cc[f.cluster] ||= []).push(f.taskId); });
console.log('\nCluster sizes:');
Object.entries(cc).sort().forEach(([k, v]) => console.log(' ', k.padEnd(20), v.length.toString().padStart(2), v.slice(0, 10).join(',') + (v.length > 10 ? ',…' : '')));
