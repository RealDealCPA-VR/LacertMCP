// Build Todo.md Phase-15 implementation-plan addendum from audit-findings-r2.json
const fs = require('fs');
const findings = JSON.parse(fs.readFileSync('C:/Users/VR/Projects/LacertMCP/audit-findings-r2.json', 'utf8'));

let out = '\n---\n\n## Phase 15 — Round-2 audit implementation plan (2026-05-30)\n\n';
out += 'Generated by a 12-lens deep audit + adversarial verification (98 agents, 78/86 confirmed). ';
out += 'Full per-task context in `audit-findings-r2.json` at repo root. Ordering: severity, then lens.\n\n';
out += '**Pre-pass (BLOCKER — landed before parallel wave to unblock downstream):**\n';
out += '- P15-001 — Over-redaction regression from P14-018/P14-019. Split WireLog redaction into _diskRedactionKeys (broad) vs _wireRedactionKeys (narrow: true secrets only). WrapToolHandler uses narrow; WriteRecord uses broad.\n\n';
out += '**Parallel cluster waves (one agent per cluster, edits limited to owned file(s)):**\n\n';

// Group + render
let prevSev = '';
for (const f of findings) {
  if (f.severity !== prevSev) {
    out += '\n### ' + f.severity.toUpperCase() + ' severity\n\n';
    prevSev = f.severity;
  }
  const title = (f.title || '').replace(/\n/g, ' ').trim();
  out += '- [ ] **' + f.taskId + '** [' + f.lens + ' / ' + f.cluster + '] ' + title + '\n';
  out += '  - File(s): ' + ((f.file || 'n/a').replace(/\\/g, '/')) + ' (line ' + (f.line || 'n/a') + ')\n';
  const desc = (f.description || '').replace(/\n/g, ' ').trim();
  out += '  - Why: ' + desc.split(/(?<=\.)\s/)[0].slice(0, 280) + '\n';
  const rec = (f.verdict && f.verdict.refinedRecommendation ? f.verdict.refinedRecommendation : (f.recommendation || '')).replace(/\n/g, ' ').trim();
  out += '  - Do: ' + rec.slice(0, 500) + (rec.length > 500 ? '...' : '') + '\n';
}

fs.writeFileSync('C:/Users/VR/Projects/LacertMCP/.todo-phase15-addendum.md', out);
console.log('Wrote', out.length, 'chars to .todo-phase15-addendum.md');
console.log('Task IDs: P15-001 through P15-' + String(findings.length).padStart(3, '0'));
