// Builds Todo.md Phase-14 addendum from audit-findings.json
const fs = require('fs');

const findings = JSON.parse(fs.readFileSync('C:/Users/VR/Projects/LacertMCP/audit-findings.json', 'utf8'));

const sevOrder = { high: 0, medium: 1, low: 2 };
findings.sort((a, b) => {
  const s = sevOrder[a.severity] - sevOrder[b.severity];
  if (s !== 0) return s;
  return a.lens.localeCompare(b.lens);
});

findings.forEach((f, i) => { f.taskId = 'P14-' + String(i + 1).padStart(3, '0'); });
fs.writeFileSync('C:/Users/VR/Projects/LacertMCP/audit-findings.json', JSON.stringify(findings, null, 2));

let out = '\n---\n\n## Phase 14 — Discovered improvements (2026-05-30 deep-audit fan-out)\n\n';
out += 'Generated by a 10-lens audit + adversarial verification workflow (88 agents, 71/78 confirmed). ';
out += 'Each task references an audit ID; full per-task context lives in `audit-findings.json` at repo root.\n';
out += 'Ordering: severity (high → low), then lens.\n';

let prevSev = '';
for (const f of findings) {
  if (f.severity !== prevSev) {
    out += '\n### ' + f.severity.toUpperCase() + ' severity\n\n';
    prevSev = f.severity;
  }
  const title = (f.title || '').replace(/\n/g, ' ').trim();
  out += '- [ ] **' + f.taskId + '** [' + f.lens + '] ' + title + '\n';
  out += '  - File(s): ' + ((f.file || 'n/a').replace(/\\/g, '/')) + ' (line ' + (f.line || 'n/a') + ')\n';
  const desc = (f.description || '').replace(/\n/g, ' ').trim();
  const firstSentence = desc.split(/(?<=\.)\s/)[0];
  out += '  - Why: ' + (firstSentence || desc).slice(0, 280) + '\n';
  const rec = (f.verdict && f.verdict.refinedRecommendation ? f.verdict.refinedRecommendation : (f.recommendation || '')).replace(/\n/g, ' ').trim();
  out += '  - Do: ' + rec.slice(0, 500) + (rec.length > 500 ? '...' : '') + '\n';
}

fs.writeFileSync('C:/Users/VR/Projects/LacertMCP/.todo-phase14-addendum.md', out);
console.log('Wrote', out.length, 'chars to .todo-phase14-addendum.md');
console.log('Task IDs: P14-001 through P14-' + String(findings.length).padStart(3, '0'));
